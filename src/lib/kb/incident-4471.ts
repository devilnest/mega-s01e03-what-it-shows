import reports from '#lib/data/reports-4471.json';
import notes from '#lib/data/desk-notes.json';
import { groupByCause, uniqueById, type Report } from '#lib/kb/causes';
import { tenantOf } from '#lib/kb/locales';
export const raw = reports as Report[];
export const merged = uniqueById(raw).filter(r => r.mergedInto === 4471);
export const groups = groupByCause(merged, tenantOf);
export const flagged = merged.filter(r => notes.oneDayMove.includes(r.id));
export const mismatches = groups.reduce((n,g) => n + g.reports.filter(r => r.meta.intakeTag !== g.cause).length, 0);
const received = merged.map(r=>r.receivedAt.slice(0,10)).sort();
const mergeDates = merged.flatMap(r=>r.mergedAt ? [r.mergedAt.slice(0,10)] : []).sort();
export const firstReceived = received[0];
export const lastReceived = received.at(-1)!;
export const firstMerged = mergeDates[0];
export const firstBatch = merged.filter(r=>r.mergedAt?.slice(0,10) === firstMerged).length;
export const earlierReports = merged.filter(r=>r.receivedAt.slice(0,10) < firstMerged).length;
export const afterKnown = merged.filter(r=>r.receivedAt.slice(0,10) > '2026-09-30').length;
const end = new Date(lastReceived+'T00:00:00Z');
end.setUTCDate(end.getUTCDate()+((8-end.getUTCDay())%7 || 7));
export const timelineEnd = end.toISOString().slice(0,10);
